-- บันทึกการจ่ายยาเสพติด/วัตถุออกฤทธิ์

CREATE TABLE IF NOT EXISTS `controlled_drug_dispense` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `drug_type` ENUM('narcotic','psychotropic') NOT NULL,
  `service_date` DATE NOT NULL,
  `service_mode` ENUM('opd','ipd') NOT NULL,
  `unit_code` VARCHAR(30) NOT NULL DEFAULT '',
  `unit_name` VARCHAR(255) NOT NULL DEFAULT '',
  `hn` VARCHAR(20) NOT NULL DEFAULT '',
  `vn` VARCHAR(20) NOT NULL DEFAULT '',
  `an` VARCHAR(20) NOT NULL DEFAULT '',
  `ptname` VARCHAR(255) NOT NULL DEFAULT '',
  `ward_name` VARCHAR(255) NOT NULL DEFAULT '',
  `bedno` VARCHAR(50) NOT NULL DEFAULT '',
  `hosxp_guid` VARCHAR(50) NOT NULL DEFAULT '',
  `item_no` INT NULL,
  `icode` VARCHAR(20) NOT NULL,
  `drug_name` VARCHAR(255) NOT NULL DEFAULT '',
  `unit` VARCHAR(50) NOT NULL DEFAULT '',
  `order_qty` DECIMAL(14,4) NOT NULL DEFAULT 0,
  `dispense_qty` DECIMAL(14,4) NULL,
  `drug_remains_qty` DECIMAL(14,4) NULL,
  `drug_remains_received_qty` DECIMAL(14,4) NULL,
  `form_received` TINYINT(1) NOT NULL DEFAULT 0,
  `receiver_name` VARCHAR(255) NOT NULL DEFAULT '',
  `preparer_name` VARCHAR(255) NOT NULL DEFAULT '',
  `dispenser_name` VARCHAR(255) NOT NULL DEFAULT '',
  `receiver_signature` MEDIUMTEXT NULL,
  `dispenser_signature` MEDIUMTEXT NULL,
  `note` VARCHAR(500) NULL,
  `status` ENUM('pending','prepared','completed') NOT NULL DEFAULT 'pending',
  `dispensed_at` DATETIME NULL,
  `prepared_at` DATETIME NULL,
  `user_id` INT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_cdm_dispense_guid` (`drug_type`, `hosxp_guid`),
  KEY `idx_cdm_dispense_date` (`drug_type`, `service_date`, `service_mode`),
  KEY `idx_cdm_dispense_unit` (`drug_type`, `service_date`, `service_mode`, `unit_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
