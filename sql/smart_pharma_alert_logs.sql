CREATE TABLE IF NOT EXISTS smart_pharma_alert_logs (
    id INT AUTO_INCREMENT PRIMARY KEY,
    alert_uid VARCHAR(191) NOT NULL,
    hn VARCHAR(20) NOT NULL,
    vn VARCHAR(20) NULL DEFAULT '',
    an VARCHAR(20) NULL DEFAULT '',
    patient_type ENUM('OPD','IPD') NOT NULL DEFAULT 'OPD',
    screen_date DATE NOT NULL,
    vstdate DATE NOT NULL,
    ptname VARCHAR(200) NULL DEFAULT '',
    rxdate DATE NULL DEFAULT NULL,
    rxtime VARCHAR(20) NULL DEFAULT '',
    ward_display VARCHAR(120) NULL DEFAULT '',
    module_key VARCHAR(32) NOT NULL,
    alert_level VARCHAR(10) NOT NULL DEFAULT 'soft',
    alert_summary VARCHAR(500) NULL DEFAULT '',
    alert_details TEXT NULL,
    status ENUM('pending','resolved') NOT NULL DEFAULT 'pending',
    resolved_by VARCHAR(20) NULL DEFAULT NULL,
    has_pharmacist_note TINYINT(1) NOT NULL DEFAULT 0,
    first_detected_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    last_seen_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP NULL DEFAULT NULL,
    UNIQUE KEY uk_alert_uid (alert_uid),
    KEY idx_status_date (status, screen_date, patient_type),
    KEY idx_hn (hn),
    KEY idx_screen (screen_date, patient_type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8;
